/**
 * LANBeam — persistent application state.
 *
 * Wraps electron-store for paired devices, settings, and transfer history.
 * Settings here are the *source of truth* that both the renderer and the
 * Rust core read from when configuring the transfer engine.
 */
import Store from 'electron-store';
import { v4 as uuidv4 } from 'uuid';

export interface PairedDevice {
  online?: boolean;        // Live presence (runtime only, never persisted)
  deviceId: string;        // Stable UUID generated by the remote peer
  name: string;            // Human-readable name (e.g. "Galaxy S24")
  kind: 'phone' | 'desktop' | 'unknown';
  fingerprint: string;    // Public-key fingerprint (currently a sha256 of pairing secret)
  pairedAt: number;        // Unix ms
  lastSeen: number;        // Unix ms
  // Live network identity — captured from the HTTP layer at pairing time and
  // refreshed on every authenticated request (heartbeat / polls). Used by the
  // device info popup so the user always sees accurate connection details.
  ip?: string;             // Last-known LAN IPv4 of the device
  userAgent?: string;      // Browser User-Agent (phone browsers only)
}

export interface Settings {
  chunkSizeMB: number;          // 1..16, default 4 (optimal balance between throughput & recovery)
  maxParallelStreams: number;   // 1..32, default 4 (sweet spot for LAN & hotspot stability)
  compressionMode: 'auto' | 'on' | 'off';   // default 'auto'
  warnOnSlowWifi: boolean;      // default true
  accentColor: string;          // hex, default '#00E5FF'
  quicPort: number;             // default 0 = random
  httpPort: number;             // default 0 = random
  fontChoice?: 'figtree' | 'outfit' | 'system'; // default 'figtree'
  showHistory?: boolean;        // default false
  // UI scale for high-DPI panels. 'auto' picks a sensible default from the
  // primary display's resolution + OS scale factor (200% on 4K, 175% on 2K
  // when the OS itself is at 100%, 100% otherwise). User can override.
  uiScale?: 'auto' | '1.0' | '1.25' | '1.5' | '1.75' | '2.0';
  acceptUnpairedAuto: boolean;  // FORCED false in security layer; UI can show but not set
  // How the desktop handles incoming files from paired devices:
  //   'auto' — land straight in Downloads with a toast (previous behaviour)
  //   'ask'  — hold the transfer and pop an Accept / Decline card first
  receiveMode?: 'auto' | 'ask';   // default 'auto'
  sendQueueMode?: 'simultaneous' | 'sequential'; // default 'sequential'
  // How throughput is DISPLAYED on both ends (PC + mirrored to the phone via
  // /api/state): megabits, megabytes, gigabytes or gigabits per second.
  speedUnit?: 'mbps' | 'mBps' | 'gBps' | 'gbps';   // default 'mBps'
  // Custom folder for incoming files/folders. Empty/undefined = default
  // (Downloads/LANBeam).
  downloadDir?: string;
}

export interface TransferHistoryEntry {
  id: string;
  fileName: string;
  fileSize: number;
  direction: 'in' | 'out';
  peerName: string;
  filePath?: string;
  startedAt: number;
  completedAt: number;
  durationMs: number;
  averageThroughputMbps: number;
  integrityOk: boolean;
  chunkRetries: number;
  status?: 'complete' | 'cancelled' | 'failed';
}

export interface AppState {
  pairedDevices: PairedDevice[];
  settings: Settings;
  history: TransferHistoryEntry[];
  localDeviceId: string;
}

const DEFAULT_SETTINGS: Settings = {
  chunkSizeMB: 4,
  maxParallelStreams: 4,
  compressionMode: 'auto',
  warnOnSlowWifi: true,
  accentColor: '#00E5FF',
  fontChoice: 'figtree',
  showHistory: false,
  uiScale: 'auto',
  quicPort: 0,
  httpPort: 54321,
  acceptUnpairedAuto: false, // hard-locked
  receiveMode: 'auto',
  sendQueueMode: 'sequential',
  speedUnit: 'mBps',
};

export class StateStore {
  private store: Store<AppState>;

  constructor() {
    this.store = new Store<AppState>({
      name: 'lanbeam-state',
      defaults: {
        pairedDevices: [],
        settings: DEFAULT_SETTINGS,
        history: [],
        localDeviceId: uuidv4(),
      },
    });
    // In-memory cache: every read is free, every write is debounced into ONE
    // disk flush. electron-store writes synchronously (whole JSON file) on
    // each set(), which stalled the main process on every heartbeat/chunk.
    this.cache = { ...(this.store.store as AppState) };
  }

  private cache: AppState;
  private flushTimer: NodeJS.Timeout | null = null;

  private read<K extends keyof AppState>(key: K): AppState[K] {
    return this.cache[key];
  }

  private write<K extends keyof AppState>(key: K, value: AppState[K]): void {
    this.cache[key] = value;
    if (this.flushTimer) return;
    this.flushTimer = setTimeout(() => { this.flushTimer = null; this.flush(); }, 400);
  }

  /** Persist now (called on quit). */
  flush(): void {
    if (this.flushTimer) { clearTimeout(this.flushTimer); this.flushTimer = null; }
    try { this.store.store = this.cache; } catch { /* best-effort */ }
  }

  get settings(): Settings {
    return { ...this.read('settings') };
  }

  updateSettings(patch: Partial<Settings>): Settings {
    const next = { ...this.read('settings'), ...patch };
    // Security: never persist acceptUnpairedAuto=true.
    next.acceptUnpairedAuto = false;
    this.write('settings', next);
    return next;
  }

  // Live presence — owned by the HTTP layer (open presence streams, in-flight
  // requests, heartbeats). In-memory only; never persisted.
  private onlineIds = new Set<string>();

  get pairedDevices(): PairedDevice[] {
    return this.read('pairedDevices').map(d => ({ ...d, online: this.onlineIds.has(d.deviceId) }));
  }

  /** Returns true when the online state actually changed. */
  setOnline(deviceId: string, online: boolean): boolean {
    if (online === this.onlineIds.has(deviceId)) return false;
    if (online) this.onlineIds.add(deviceId); else this.onlineIds.delete(deviceId);
    return true;
  }

  onlineDeviceIds(): string[] {
    return [...this.onlineIds];
  }

  /**
   * Find the record that IS this physical device, however it arrives:
   * stable deviceId, pair-secret hash, or same name+kind from the same LAN IP.
   */
  findSameDevice(q: { deviceId?: string; fingerprint?: string; name?: string; kind?: string; ip?: string }): PairedDevice | undefined {
    const list = this.read('pairedDevices');
    return (
      (q.deviceId ? list.find(d => d.deviceId === q.deviceId) : undefined) ||
      (q.fingerprint ? list.find(d => d.fingerprint === q.fingerprint) : undefined) ||
      (q.ip && q.name ? list.find(d => d.ip === q.ip && d.name === q.name && d.kind === (q.kind ?? d.kind)) : undefined)
    );
  }

  addPairedDevice(input: PairedDevice): void {
    const { online: _ignored, ...device } = input as PairedDevice;
    const now = Date.now();
    // Read from the live CACHE (never the debounced disk copy) so no write is lost.
    const devices = this.read('pairedDevices').filter(d => {
      if (d.deviceId === device.deviceId) return false;
      if (d.kind !== device.kind || d.name !== device.name) return true;
      // Same physical device = same name+kind AND (same LAN IP, or same
      // browser UA while offline, or a ghost unseen for 2+ minutes).
      if (d.ip && device.ip && d.ip === device.ip) return false;
      const offline = !this.onlineIds.has(d.deviceId);
      if (offline && d.userAgent && device.userAgent && d.userAgent === device.userAgent) return false;
      return !(offline && now - (d.lastSeen || 0) >= 2 * 60 * 1000);
    });
    // A re-pair keeps the original pairing date.
    const prev = this.read('pairedDevices').find(d => d.deviceId === device.deviceId);
    if (prev?.pairedAt) device.pairedAt = prev.pairedAt;
    devices.unshift(device);
    this.write('pairedDevices', devices);
  }

  /** Drop records that haven't been seen for `maxAgeMs` (default 90 days). */
  prunePairedDevices(maxAgeMs = 90 * 24 * 60 * 60 * 1000): number {
    const cutoff = Date.now() - maxAgeMs;
    const devices = this.read('pairedDevices');
    const kept = devices.filter(d => (d.lastSeen || 0) >= cutoff);
    const removed = devices.length - kept.length;
    if (removed > 0) this.write('pairedDevices', kept);
    return removed;
  }

  /**
   * One-tap roster cleanup: remove every device that is not currently
   * online (lastSeen older than `onlineMs`, default 2 minutes). The Devices
   * page "Clear offline" button calls this — instantly clears walls of
   * stale entries without touching live devices.
   */
  clearOfflineDevices(onlineMs = 2 * 60 * 1000): { removed: number; kept: PairedDevice[] } {
    const devices = this.read('pairedDevices');
    const kept = devices.filter(d => this.onlineIds.has(d.deviceId));
    const removed = devices.length - kept.length;
    if (removed > 0) this.write('pairedDevices', kept);
    return { removed, kept: this.pairedDevices };
  }

  /** Remove any duplicate deviceIds, keeping the one with the newest lastSeen. */
  deduplicatePairedDevices(): void {
    const seen = new Map<string, PairedDevice>();
    for (const d of this.read('pairedDevices')) {
      const existing = seen.get(d.deviceId);
      if (!existing || d.lastSeen > existing.lastSeen) seen.set(d.deviceId, d);
    }
    // Also collapse same name+kind+IP clones left over from older builds.
    const byKey = new Map<string, PairedDevice>();
    for (const d of [...seen.values()].sort((a, b) => b.lastSeen - a.lastSeen)) {
      const key = d.ip ? `${d.kind}::${d.name}::${d.ip}` : `id::${d.deviceId}`;
      if (!byKey.has(key)) byKey.set(key, d);
    }
    const list = [...byKey.values()];
    this.write('pairedDevices', list);
  }

  removePairedDevice(deviceId: string): void {
    this.onlineIds.delete(deviceId);
    this.write('pairedDevices', this.read('pairedDevices').filter(d => d.deviceId !== deviceId));
  }

  touchPairedDevice(deviceId: string, meta?: { ip?: string; userAgent?: string }): void {
    const d = this.read('pairedDevices').find(x => x.deviceId === deviceId);
    if (!d) return;
    const now = Date.now();
    const changed = (meta?.ip && meta.ip !== d.ip) || (meta?.userAgent && meta.userAgent !== d.userAgent);
    // Presence only needs ~3s granularity; skip the write storm otherwise.
    if (!changed && now - (d.lastSeen || 0) < 3000) return;
    d.lastSeen = now;
    if (meta?.ip) d.ip = meta.ip;
    if (meta?.userAgent) d.userAgent = meta.userAgent;
    this.write('pairedDevices', this.read('pairedDevices'));
  }

  get history(): TransferHistoryEntry[] {
    return [...this.read('history')];
  }

  addHistory(entry: TransferHistoryEntry): void {
    const history = [entry, ...this.read('history')].slice(0, 500);
    this.write('history', history);
  }

  get localDeviceId(): string {
    return this.read('localDeviceId');
  }
}
